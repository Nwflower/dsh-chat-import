// ── 6. metaMessages 计数（失败要大声） ──
test('claude isMeta: metaMessages 计数识别到的 isMeta 记录数', () => {
  const out = convertClaudeJsonl(jsonl([
    user('提问'),
    asst([{ type: 'text', text: '回答' }]),
    meta('meta-1'),
    meta([{ type: 'text', text: 'meta-2' }, { type: 'text', text: 'meta-3' }]),
    // 结构块（无 text）：仍算一条 isMeta 记录，但没有文本可前置
    meta([{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'AAAA' } }]),
    // content 形态怪异（对象）：同样不得变成空 prompt 假轮
    meta({ unexpected: true }),
  ]), { fileStem: SID })

  assert.equal(out.turns.length, 1, '4 条 isMeta 记录都不得开新轮')
  assert.equal(out.metaMessages, 4)
  assert.equal(out.turns[0].steps.length, 1, 'meta 不拆步')
  // 有文本的三条合并成一块追加到当前轮最后一步末尾；结构块（image）无文本可留
  assert.deepEqual(out.turns[0].steps[0].content, [
    { type: 'text', text: '回答' },
    { type: 'text', text: 'meta-1\nmeta-2\nmeta-3' },
  ])
  assert.equal(out.droppedUserPrompts, 0, 'isMeta 记录不计入无法解析的 user 消息')
})


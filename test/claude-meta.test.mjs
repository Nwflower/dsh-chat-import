// ── 7. 中途切 model：各步带各 step.model，会话级 model 取第一条兜底 ──
test('claude step.model: 各 assistant 步骤记录自己的 model，会话级 model 取第一条', () => {
  const out = convertClaudeJsonl(jsonl([
    user('问题1'),
    asst([{ type: 'text', text: '答1' }], 'claude-sonnet-4-5'),
    user('问题2'),
    asst([{ type: 'text', text: '答2' }], 'claude-opus-4-7'),
    // 无 model 字段的 assistant：不写 step.model，回落会话级 model
    asst([{ type: 'text', text: '答3' }]),
  ]), { fileStem: SID })

  assert.equal(out.turns.length, 2)
  assert.deepEqual(out.turns[0].steps.map((s) => s.model), ['claude-sonnet-4-5'])
  assert.deepEqual(out.turns[1].steps.map((s) => s.model), ['claude-opus-4-7', undefined])
  const sources = assistantEvents(out).map((e) => e.data.message.source.model)
  assert.deepEqual(sources, ['claude-sonnet-4-5', 'claude-opus-4-7', 'claude-sonnet-4-5'])
})

// ── 7b. isMeta 之后切的 model：meta 前置不改变 step.model ──
test('claude step.model: isMeta 前置到带新 model 的步骤后，该步仍记自己的 model', () => {
  const out = convertClaudeJsonl(jsonl([
    user('问题'),
    asst([{ type: 'text', text: '答1' }], 'claude-sonnet-4-5'),
    meta('Continue from where you left off.'),
    asst([{ type: 'text', text: '答2' }], 'claude-opus-4-7'),
  ]), { fileStem: SID })

  assert.deepEqual(out.turns[0].steps.map((s) => s.model), ['claude-sonnet-4-5', 'claude-opus-4-7'])
  assert.deepEqual(out.turns[0].steps[1].content, [
    { type: 'text', text: 'Continue from where you left off.' },
    { type: 'text', text: '答2' },
  ])
  assert.equal(assistantEvents(out)[1].data.message.source.model, 'claude-opus-4-7')
})

// ── 8. firstTopicPrompt 行为不变（注入块与粘贴信封口径照旧） ──
test('claude isMeta: firstTopicPrompt 行为不变（跳过注入块取首个真实提问；粘贴信封剥离正文）', () => {
  // 注入块（此处为 isMeta：不是提问、不作标题）、斜杠命令日志之后的真实提问才是话题
  const injected = convertClaudeJsonl(jsonl([
    meta('<local-command-caveat>Caveat: 本地命令输出</local-command-caveat>'),
    user('<command-name>/model</command-name> <command-message>model</command-message>'),
    user('继续处理'),
    asst([{ type: 'text', text: '好。' }]),
  ]), { fileStem: SID })
  assert.equal(injected.title, '继续处理')
  assert.equal(injected.turns.length, 2, '斜杠命令日志仍按既有行为开轮（只是不作标题），isMeta 不开轮')

  // 粘贴信封剥离后作标题
  const pasted = convertClaudeJsonl(jsonl([
    user('<pasted_content id="1b70">\n首页改成下面的样子：1. …\n</pasted_content>'),
    asst([{ type: 'text', text: '好。' }]),
  ]), { fileStem: SID })
  assert.equal(pasted.title, '首页改成下面的样子：1. …')

  // 全是注入块 → 无话题（不钉标题）
  const onlyInjected = convertClaudeJsonl(jsonl([
    user('<local-command-caveat>Caveat: 只有本地命令</local-command-caveat>'),
    asst([{ type: 'text', text: '好。' }]),
  ]), { fileStem: SID })
  assert.equal(onlyInjected.title, '')
  assert.equal(onlyInjected.events.some((e) => e.type === 'session/title'), false)
})
